const COST_BY_SLUG = Object.fromEntries(COSTS.map((c) => [c.slug, c]));

export function getCost(slug: string): CostDef | undefined {
  return COST_BY_SLUG[slug];
}
export function allCostSlugs(): string[] {
  return COSTS.map((c) => c.slug);
}
export function hasCost(slug: string): boolean {
  return Boolean(COST_BY_SLUG[slug]);
}
export function costCanonical(slug: string): string {
  return `${SITE.domain}/cost/${slug}/`;
}

/** 비용 페이지 표시명 — 업종명 + "앱 개발 비용" */
export function costTitleName(slug: string): string {
  const ind = getIndustry(slug);
  const base = ind?.ko ?? slug;
  return `${base} 앱 개발 비용`;
}

/**
 * 비용 페이지 색인 판정 — 실제 렌더되는 본문(lead·tiers·drivers·running·save·FAQ)에서
 * 신호를 측정한다. peerFingerprints 는 다른 비용 페이지의 고유 지문(lead+drivers+running)과
 * 대조해 비용 페이지끼리의 중복만 검사한다(/app 축과는 검색 의도가 분리되어 있음).
 * 내부링크: 브레드크럼 2 + /app 대응 페이지 1 + 다른 비용 페이지 min(6) + 하단 요금 1.
 */
export function costDecision(slug: string): IndexDecision | null {
  const c = getCost(slug);
  if (!c) return null;
  const ind = getIndustry(slug);
  const name = costTitleName(slug);
  const others = COSTS.filter((x) => x.slug !== c.slug);
  const internalLinks = 2 + 1 + Math.min(others.length, 6) + 1;
  return decideFromContent({
    title: `${name} | 가격대·비용 구성·절감 방법 — 름랩`,
    description: `${name} 얼마나 들까요? 간단형·표준형·고급형 가격대와 비용을 좌우하는 요인, 유지비, 절감 방법까지 정리했습니다. 소스코드 이관·월 관리비 없음.`,
    h1: name,
    bodyParts: [
      c.lead,
      c.tiers.map((t) => `${t.name} ${t.range} ${t.scope}`),
      c.drivers,
      c.running,
      c.save,
      ...c.faqs.map((f) => f.a),
      ind?.coreFeatures,
    ],
    faqQuestions: c.faqs.map((f) => f.q),
    internalLinks,
    hasUniqueMedia: false,
    // 비용 페이지 고유성 비교 — 다른 비용 페이지의 lead+drivers+running 지문과 대조
    peerFingerprints: others.map((x) => fingerprint(`${x.lead} ${x.drivers.join(' ')} ${x.running}`)),
  });
}
