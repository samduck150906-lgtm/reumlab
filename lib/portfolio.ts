export interface PortfolioItem {
  /** URL 슬러그 (로마자, 케밥케이스) */
  slug: string;
  /** 프로젝트명 (익명 가능) */
  title: string;
  /** 한 줄 요약 */
  summary: string;
  category: 'app' | 'web' | 'ai';
  /** 기술 스택 */
  stack: string[];
  /** 문제 → 해결 → 결과 (사례 페이지 본문 골격) */
  problem: string;
  solution: string;
  result: string;
  /** 산출물 (소스코드/저장소/문서/교육/권한 등) */
  deliverables: string[];
  /** 화면에서 확인되는 핵심 기능·특징 (불릿) */
  highlights?: string[];
  /** /public 기준 실제 작업 화면 이미지 (없으면 생략) */
  images?: { src: string; alt: string }[];
  durationDays?: number;
  /** ISO 날짜 (YYYY-MM-DD) */
  publishedAt: string;
  /** 공개 동의 상태 — 미동의면 익명 처리 */
  consent?: 'named' | 'anonymous';
  /** 상세 페이지 검색 키워드 (메타 keywords) */
  keywords?: string[];
  /** 상세 페이지 title 오버라이드 (없으면 자동 생성) */
  metaTitle?: string;
  /** 상세 페이지 description 오버라이드 (없으면 summary 사용) */
  metaDescription?: string;
  /** 사용 기술을 "왜 이 스택인지" 한 문단으로 (기술 신뢰 신호) */
  techNote?: string;
  /** 개발 범위 — 실제로 만든 화면·기능 단위 (불릿) */
  scope?: string[];
  /** 비개발자 대표가 같은 걸 의뢰할 때 확인할 체크포인트 (불릿) */
  checkpoints?: string[];
  /** 비슷한 규모를 새로 만들 때 예상 견적 — 실제 정액 패키지 기준(추정 수치 금지) */
  estimateNote?: string;
  /** 상세 페이지 고유 FAQ (FAQPage 스키마 + 본문) — 사실 확인된 범위만 */
  faqs?: { q: string; a: string }[];
}

