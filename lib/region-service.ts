/**
 * 비대면 진행 안내 — 지역 그룹에 따라 실제로 달라지는 내용만 다르게 쓴다.
 * 사업장은 동탄 한 곳이고 전국 비대면으로 진행한다는 사실 위에서, 거리에 따라
 * "대면이 가능한지"만 정직하게 구분한다. 없는 지사를 있는 것처럼 쓰지 않는다.
 */
export function remoteWorkNote(group: string, regionFull: string): string {
  if (group === '경기-본거지' || group === '경기-인접') {
    return `름랩 사업장은 화성 동탄에 있습니다. ${regionFull}은 이동 거리가 짧아 일정만 맞으면 대면 상담이 가능하지만, 화상·메신저로 화면과 문서를 함께 확인할 수도 있습니다. 대면 장소·참석자·일정은 사전에 협의합니다.`;
  }
  if (group === '수도권' || group === '서울-핵심' || group === '서울-스타트업' || group.startsWith('경기')) {
    return `름랩 사업장은 화성 동탄에 있고, ${regionFull} 프로젝트는 비대면으로 진행합니다. 상담·화면 확인·중간 점검을 화상과 메신저로 하고, 소스코드와 문서는 저장소로 그대로 넘겨 드립니다. 필요하면 일정을 조율해 대면도 가능하지만, 진행에 반드시 필요한 절차는 아닙니다.`;
  }
  return `${regionFull}처럼 거리가 있는 지역도 같은 조건으로 진행합니다. 름랩은 상담부터 화면 확인·중간 점검·납품·운영 교육까지 비대면으로 진행하는 것을 기본으로 하고 있어, 방문 없이도 진행 방식이나 결과물이 달라지지 않습니다. 견적은 개발 범위로 정하며, 출장·현장 설치가 필요하면 해당 조건과 비용을 별도로 협의합니다.`;
}
