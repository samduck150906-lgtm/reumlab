const SERVICE_BY_SLUG = Object.fromEntries(SERVICES.map((s) => [s.slug, s]));
const REGION_BY_SLUG = Object.fromEntries(REGIONS.map((r) => [r.slug, r]));

export function getService(slug: string): ServiceDef | undefined {
  return SERVICE_BY_SLUG[slug];
}
export function getRegion(slug: string): RegionDef | undefined {
  return REGION_BY_SLUG[slug];
}

/** 모든 서비스×지역 조합 (generateStaticParams + sitemap) */
export function allRegionServiceParams(): { slug: string; region: string }[] {
  const out: { slug: string; region: string }[] = [];
  for (const s of SERVICES) for (const r of REGIONS) out.push({ slug: s.slug, region: r.slug });
  return out;
}

/** 같은 서비스의 다른 지역 (내부링크 스포크) — 같은 group(상권 클러스터) 우선 노출.
 *  모든 페이지가 동일한 6개만 링크하던 문제를 해결해 꼬리 지역까지 내부링크가 고루 분산된다. */
export function siblingRegions(serviceSlug: string, regionSlug: string, n = 6): RegionDef[] {
  const self = REGION_BY_SLUG[regionSlug];
  const others = REGIONS.filter((r) => r.slug !== regionSlug);
  if (!self) return others.slice(0, n);
  const sameGroup = others.filter((r) => r.group === self.group);
  const rest = others.filter((r) => r.group !== self.group);
  return [...sameGroup, ...rest].slice(0, n);
}

export function regionServiceCanonical(serviceSlug: string, regionSlug: string): string {
  return `${SITE.domain}/${serviceSlug}/${regionSlug}/`;
}

/** 문자열 → 0~359 색상(hue). 같은 입력이면 항상 같은 값(결정적, SSG 안전). */
function hashHue(seed: string): number {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) % 360;
  return h;
}

export interface RegionServiceMedia {
  /** 페이지마다 고유한 대체 텍스트 (색인 게이트의 hasUniqueMedia 근거) */
  alt: string;
  /** 상권 그룹×서비스로 결정되는 배경 hue (지역마다 다른 톤) */
  hue: number;
  /** 히어로에 표시할 메인 라벨 */
  label: string;
  /** 보조 라벨 (가격 한 줄) */
  sub: string;
}

