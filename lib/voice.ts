const CTA_PRIMARY = [
  '상담 받아보기',
  '예상 견적 확인',
  '프로젝트 이야기하기',
  '개발 가능 여부 확인',
  '상담 범위 확인',
  '일단 물어보기',
  '견적 먼저 받아보기',
];

/** 페이지별 1차 CTA 라벨 (전화/상담 버튼) */
export function ctaPrimary(seed: string): string {
  return pick(CTA_PRIMARY, seed, 'cta');
}

