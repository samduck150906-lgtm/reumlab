/**
 * 사람 손맛 — CTA 라벨과 운영자 어투 문장을 페이지마다 다르게 고른다.
 *
 * 프로그래매틱 페이지가 전부 똑같은 "무료 상담" 버튼과 똑같은 톤으로 찍혀 나오면
 * 기계로 뽑은 티가 난다. 슬러그를 시드로 결정적(SSG 안전)으로 골라, 같은 페이지는
 * 항상 같은 문구를 쓰되 페이지끼리는 서로 달라지게 한다.
 *
 * Date.now()/Math.random() 미사용 — 빌드마다 값이 흔들리면 하이드레이션이 깨진다.
 */

/** FNV-1a 해시 → 음이 아닌 정수 (결정적) */
function hashInt(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function pick<T>(pool: T[], seed: string, salt = ''): T {
  return pool[hashInt(seed + '|' + salt) % pool.length];
}

