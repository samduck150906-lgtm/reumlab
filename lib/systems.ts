/** 업종 페이지에서 이어 붙일 시스템 목록 (없으면 빈 배열) */
export function systemsForIndustry(industrySlug: string): SystemDef[] {
  return (SYSTEMS_BY_INDUSTRY[industrySlug] ?? [])
    .map((s) => getSystem(s))
    .filter((s): s is SystemDef => Boolean(s));
}

export function getSystem(slug: string): SystemDef | undefined {
  return SYSTEMS.find((s) => s.slug === slug);
}

export const SYSTEM_HUB = `${SITE.domain}/system/`;

export function systemCanonical(slug: string): string {
  return `${SITE.domain}/system/${slug}/`;
}

export function systemTitle(s: SystemDef): string {
  return `${s.primary} | 기능·비용·개발기간 정리 | 름랩`;
}

export function systemDescription(s: SystemDef): string {
  // 기능 목록을 그대로 이어 붙이면 괄호·화살표가 섞인 문장이 검색결과에 실린다.
  // 그 페이지의 도입부 첫 문장(사람이 쓴 문장)을 쓰고, 뒤에 비용·조건을 짧게 붙인다.
  const first = s.lead.split(/(?<=[.])\s/)[0].trim();
  const tail = 'VAT 포함 정액 · 소스코드 이관 · 월 관리비 없음.';
  const withNeed = `${first} 필요한 기능과 예상 비용·기간을 정리했습니다.`;
  const full = `${withNeed} ${tail}`;
  return full.length <= 155 ? full : withNeed.slice(0, 155);
}

