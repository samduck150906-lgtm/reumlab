function hasBatchim(s) {
  const ch = String(s).trim().slice(-1);
  const code = ch.charCodeAt(0);
  if (Number.isNaN(code) || code < 0xac00 || code > 0xd7a3) return false;
  return (code - 0xac00) % 28 !== 0;
}
function eunneun(s) {
  return hasBatchim(s) ? '은' : '는';
}

